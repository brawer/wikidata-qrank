// This file produces a CycloneDX 1.7 Bill of Materials for one dated QRank
// file: the exact bytes that were produced (SHA-256 and SHA-512), the item
// signals it was computed from, which versions of the Wikimedia dumps,
// pageviews and OSMViews went into those, and which versions of
// qrank-builder processed them. The builder stores it as
// public/qrank-YYYYMMDD.cdx.json, before the QRank file itself.
//
// QRank reuses intermediate files from earlier runs, so a single QRank file
// can be the work of several qrank-builder releases. They are all listed in
// metadata.tools and referenced from the one "QRank build" workflow; the
// internal pipeline steps are not exposed. The versions come from the item
// signals provenance record (see provenance.go).
//
// The BOM is generated by hand rather than with a CycloneDX library to keep
// the dependency surface small and the output byte-stable: encoding/json
// emits struct fields in declaration order, and every input is deterministic
// (the data date, not the wall clock).

const (
	bomSpecVersion = "1.7"
	bomSchema      = "http://cyclonedx.org/schema/bom-1.7.schema.json"

	bomWebsiteURL   = "https://qrank.toolforge.org/"
	bomDownloadURL  = "https://qrank.toolforge.org/download/"
	bomVCSURL       = "https://github.com/brawer/wikidata-qrank"
	bomBuildSysURL  = "https://github.com/brawer/wikidata-qrank/actions"
	bomDumpsURL     = "https://dumps.wikimedia.org/"
	bomPageviewsURL = "https://dumps.wikimedia.org/other/pageview_complete/"

	// bomSupplier{Name,URL} identify the supplier of both the QRank file and
	// the pipeline. NTIA "minimum elements" require a supplier for the
	// document and every component.
	bomSupplierName  = "Sascha Brawer"
	bomSupplierURL   = "https://brawer.ch"
	bomWikimediaName = "Wikimedia Foundation"
	bomWikimediaURL  = "https://wikimediafoundation.org"

	// bomRepoSlug is the "<namespace>/<name>" of the pkg:github Package-URL
	// for the pipeline; bomModuleGroup is the Go module path, used as the
	// CycloneDX component group.
	bomRepoSlug    = "brawer/wikidata-qrank"
	bomModuleGroup = "github.com/brawer/wikidata-qrank/v2"

	bomDumpsRef     = "wikimedia-dumps"
	bomPageviewsRef = "wikimedia-pageviews"
	bomOSMViewsRef  = "osmviews"
	bomOSMViewsURL  = "https://osmviews.brawer.ch"
)

// bomNamespace is a fixed, arbitrary UUID. The BOM's serialNumber is a
// version-5 (SHA-1) UUID derived from it and the QRank file's SHA-256, so an
// identical QRank file always yields an identically identified BOM.
var bomNamespace = uuid.MustParse("4f0d2c6e-8b1a-4e57-9c3d-2a6b7e8f9d10")

// bomInputs is everything writeBOM needs about one build. Every field is
// deterministic; nothing is read from the wall clock.
type bomInputs struct {
	Date          time.Time              // date of the item signals; the version identity
	SHA256        string                 // lower-case hex digest of the QRank file
	SHA512        string                 // lower-case hex digest of the QRank file
	SignalsSHA256 string                 // lower-case hex digest of the item signals file
	SignalsSHA512 string                 // lower-case hex digest of the item signals file
	Provenance    *ItemSignalsProvenance // inputs and producers of the item signals
	Software      string                 // this build, e.g. "QRank/v2.2.0+1a2b3c4d5e6f"
	Revision      string                 // full VCS revision of this build, or ""
	Modified      bool                   // whether this build's working tree was dirty
}

// hashFile returns the lower-case hex SHA-256 and SHA-512 digests of the file
// at path, read in a single pass, and its size in bytes.
func hashFile(path string) (sha256hex, sha512hex string, size int64, err error) {
	f, err := os.Open(path)
	if err != nil {
		return "", "", 0, err
	}
	defer f.Close()

	h256 := sha256.New()
	h512 := sha512.New()
	size, err = io.Copy(io.MultiWriter(h256, h512), f)
	if err != nil {
		return "", "", 0, err
	}
	return hex.EncodeToString(h256.Sum(nil)), hex.EncodeToString(h512.Sum(nil)), size, nil
}

// writeBOM builds the CycloneDX BOM for in and writes it to path, atomically.
func writeBOM(path string, in bomInputs) error {
	return writeJSON(path, buildBOM(in))
}

// writeJSON encodes v as indented JSON and writes it to path, atomically.
func writeJSON(path string, v any) error {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false) // keep '&' in purl query strings literal
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		return err
	}

	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, buf.Bytes(), 0644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// builderVersion is a qrank-builder version, parsed from the software
// string that it stamps on every file it stores.
type builderVersion struct {
	Software string // e.g. "QRank/v2.2.0+1a2b3c4d5e6f"
	Release  string // e.g. "2.2.0", or ""
	Revision string // e.g. "1a2b3c4d5e6f" (possibly abbreviated), or ""
	Modified bool   // whether the working tree was dirty
}

var (
	releaseSoftwareRegexp = regexp.MustCompile(`^QRank/v(\d+\.\d+\.\d+)(?:\+([0-9a-f]+)(-modified)?)?$`)
	gitSoftwareRegexp     = regexp.MustCompile(`^QRank/git-([0-9a-f]+)(-modified)?$`)
)

func parseBuilderVersion(software string) builderVersion {
	v := builderVersion{Software: software}
	if m := releaseSoftwareRegexp.FindStringSubmatch(software); m != nil {
		v.Release, v.Revision, v.Modified = m[1], m[2], m[3] != ""
	} else if m := gitSoftwareRegexp.FindStringSubmatch(software); m != nil {
		v.Revision, v.Modified = m[1], m[2] != ""
	}
	return v
}

// Version is what the BOM gives as the tool's version: the release,
// or else the software string without its "QRank/" prefix.
func (v builderVersion) Version() string {
	if v.Release != "" {
		return v.Release
	}
	return strings.TrimPrefix(strings.TrimPrefix(v.Software, "QRank"), "/")
}

// BOMRef is the tool's identifier within the BOM.
func (v builderVersion) BOMRef() string {
	if ver := v.Version(); ver != "" {
		return "qrank-builder-" + ver
	}
	return "qrank-builder"
}

// PURL is the Package-URL of the source code. For the running build, which
// knows its full revision, it names the exact commit. Older versions only
// recorded an abbreviated revision, so it names their release tag instead.
// A modified working tree has no commit to point to.
func (v builderVersion) PURL(fullRevision string) string {
	switch {
	case fullRevision != "" && !v.Modified:
		return "pkg:github/" + bomRepoSlug + "@" + fullRevision
	case v.Release != "":
		return "pkg:github/" + bomRepoSlug + "@v" + v.Release
	case v.Revision != "" && !v.Modified:
		return "pkg:github/" + bomRepoSlug + "@" + v.Revision
	default:
		return ""
	}
}

// builderVersions returns the distinct qrank-builder versions involved
// in a build, in the order of the provenance record, with the running
// build added if it is not listed yet.
func (in bomInputs) builderVersions() []builderVersion {
	seen := make(map[string]bool)
	result := make([]builderVersion, 0, len(in.Provenance.Software)+1)
	for _, sw := range append(append([]string{}, in.Provenance.Software...), in.Software) {
		if !seen[sw] {
			seen[sw] = true
			result = append(result, parseBuilderVersion(sw))
		}
	}
	return result
}

// downloadURL is where this build's QRank file is published under its dated
// name. It is retained for only the three most recent builds; the BOM's
// hashes, not this URL, are the durable integrity anchor.
func (in bomInputs) downloadURL() string {
	return fmt.Sprintf("%sqrank-%s.csv.gz", bomDownloadURL, in.Date.UTC().Format("20060102"))
}

// dataPURL is the Package-URL of the QRank file itself: a generic package
// pinned by version date, carrying its SHA-256 and download URL as
// qualifiers (sorted, as the purl spec requires).
func (in bomInputs) dataPURL() string {
	return fmt.Sprintf("pkg:generic/qrank@%s?checksum=sha256:%s&download_url=%s",
		in.Date.UTC().Format(time.DateOnly), in.SHA256, url.QueryEscape(in.downloadURL()))
}

// signalsDownloadURL is where this build's item signals are published
// under their dated name, likewise retained for three builds only.
func (in bomInputs) signalsDownloadURL() string {
	return fmt.Sprintf("%sitem_signals-%s.parquet", bomDownloadURL, in.Date.UTC().Format("20060102"))
}

// signalsPURL is the Package-URL of the item signals file.
func (in bomInputs) signalsPURL() string {
	return fmt.Sprintf("pkg:generic/item_signals@%s?checksum=sha256:%s&download_url=%s",
		in.Date.UTC().Format(time.DateOnly), in.SignalsSHA256, url.QueryEscape(in.signalsDownloadURL()))
}

func bomSupplier() *cdxOrgEntity {
	return &cdxOrgEntity{Name: bomSupplierName, URL: []string{bomSupplierURL}}
}

func bomWikimedia() *cdxOrgEntity {
	return &cdxOrgEntity{Name: bomWikimediaName, URL: []string{bomWikimediaURL}}
}

func (in bomInputs) builderTool(v builderVersion) cdxComponent {
	var fullRevision string
	if v.Software == in.Software {
		fullRevision = in.Revision
	}
	props := []cdxProperty{{Name: "qrank:software", Value: v.Software}}
	if fullRevision != "" {
		props = append(props,
			cdxProperty{Name: "qrank:vcs:revision", Value: fullRevision},
			cdxProperty{Name: "qrank:vcs:modified", Value: strconv.FormatBool(in.Modified)})
	}
	return cdxComponent{
		Type:      "application",
		BOMRef:    v.BOMRef(),
		Supplier:  bomSupplier(),
		Name:      "qrank-builder",
		Group:     bomModuleGroup,
		Version:   v.Version(),
		Publisher: bomSupplierName,
		PURL:      v.PURL(fullRevision),
		Licenses:  []cdxLicenseChoice{{License: cdxLicense{ID: "MIT"}}},
		ExternalReferences: []cdxExternalRef{
			{Type: "vcs", URL: bomVCSURL},
			{Type: "build-system", URL: bomBuildSysURL},
		},
		Properties: props,
	}
}

func buildBOM(in bomInputs) *cdxBOM {
	date := in.Date.UTC().Format(time.DateOnly)
	ymd := in.Date.UTC().Format("20060102")
	dataRef := "qrank-" + ymd
	signalsRef := "item_signals-" + ymd
	prov := in.Provenance

	// The pipeline is a tool that produced the QRank file, not a component
	// the file depends on. It therefore lives in metadata.tools and is
	// referenced from the formulation workflow below.
	versions := in.builderVersions()
	tools := make([]cdxComponent, 0, len(versions))
	toolRefs := make([]cdxResourceRef, 0, len(versions))
	for _, v := range versions {
		tools = append(tools, in.builderTool(v))
		toolRefs = append(toolRefs, cdxResourceRef{Ref: v.BOMRef()})
	}

	data := cdxComponent{
		Type:        "data",
		BOMRef:      dataRef,
		Supplier:    bomSupplier(),
		Name:        "qrank",
		Version:     date,
		Description: "Wikidata items ranked by aggregated Wikimedia pageviews (gzip-compressed CSV, columns Entity,QRank).",
		PURL:        in.dataPURL(),
		Licenses:    []cdxLicenseChoice{{License: cdxLicense{ID: "CC0-1.0"}}},
		Hashes: []cdxHash{
			{Alg: "SHA-256", Content: in.SHA256},
			{Alg: "SHA-512", Content: in.SHA512},
		},
		ExternalReferences: []cdxExternalRef{
			{Type: "distribution", URL: in.downloadURL()},
			{Type: "website", URL: bomWebsiteURL},
			{Type: "vcs", URL: bomVCSURL},
		},
		Data: []cdxComponentData{{
			BOMRef:         "qrank-dataset-" + ymd,
			Type:           "dataset",
			Name:           "QRank",
			Classification: "PUBLIC",
		}},
	}

	// The QRank file is computed from the item signals, which
	// are published alongside it.
	signals := cdxComponent{
		Type:        "data",
		BOMRef:      signalsRef,
		Supplier:    bomSupplier(),
		Name:        "item_signals",
		Version:     date,
		Description: "Ranking signals for Wikidata items (Apache Parquet, columns item, pageviews_52w, wikitext_bytes, statement_count, identifier_count, sitelink_count, osmviews_score).",
		PURL:        in.signalsPURL(),
		Licenses:    []cdxLicenseChoice{{License: cdxLicense{ID: "CC0-1.0"}}},
		Hashes: []cdxHash{
			{Alg: "SHA-256", Content: in.SignalsSHA256},
			{Alg: "SHA-512", Content: in.SignalsSHA512},
		},
		ExternalReferences: []cdxExternalRef{
			{Type: "distribution", URL: in.signalsDownloadURL()},
			{Type: "website", URL: bomWebsiteURL},
			{Type: "vcs", URL: bomVCSURL},
		},
		Data: []cdxComponentData{{
			BOMRef:         "item_signals-dataset-" + ymd,
			Type:           "dataset",
			Name:           "Item signals",
			Classification: "PUBLIC",
		}},
	}

	// All Wikimedia database dumps are one component. Its version is the
	// newest dump date of any wiki; there is no oldest date, because some
	// archived wikis have not been dumped in years but still get pageviews.
	dumps := cdxComponent{
		Type:        "data",
		BOMRef:      bomDumpsRef,
		Supplier:    bomWikimedia(),
		Name:        "Wikimedia database dumps",
		Version:     prov.Dumps.Newest,
		Description: "Database dumps of all Wikimedia wikis. The version is the newest dump date of any wiki.",
		PURL: "pkg:generic/wikimedia-dumps@" + prov.Dumps.Newest +
			"?download_url=" + url.QueryEscape(bomDumpsURL),
		ExternalReferences: []cdxExternalRef{
			{Type: "distribution", URL: bomDumpsURL},
		},
		Properties: []cdxProperty{
			{Name: "qrank:dumps:newest", Value: prov.Dumps.Newest},
			{Name: "qrank:dumps:wikis", Value: strconv.Itoa(prov.Dumps.Wikis)},
		},
	}

	pageviews := cdxComponent{
		Type:        "data",
		BOMRef:      bomPageviewsRef,
		Supplier:    bomWikimedia(),
		Name:        "Wikimedia pageviews (pageview_complete)",
		Version:     prov.Pageviews.LastDay,
		Description: "Daily per-article pageview counts for all Wikimedia projects. The version is the last day included.",
		PURL: "pkg:generic/wikimedia-pageviews@" + prov.Pageviews.LastDay +
			"?download_url=" + url.QueryEscape(bomPageviewsURL),
		Licenses: []cdxLicenseChoice{{License: cdxLicense{ID: "CC0-1.0"}}},
		ExternalReferences: []cdxExternalRef{
			{Type: "distribution", URL: bomPageviewsURL},
		},
		Properties: []cdxProperty{
			{Name: "qrank:pageviews:firstDay", Value: prov.Pageviews.FirstDay},
			{Name: "qrank:pageviews:lastDay", Value: prov.Pageviews.LastDay},
			{Name: "qrank:pageviews:weeks", Value: strconv.Itoa(prov.Pageviews.Weeks)},
		},
	}

	components := []cdxComponent{signals, dumps, pageviews}
	inputs := []cdxWorkflowIO{
		{Resource: &cdxResourceRef{Ref: bomDumpsRef}},
		{Resource: &cdxResourceRef{Ref: bomPageviewsRef}},
	}
	signalsDeps := []string{bomDumpsRef, bomPageviewsRef}
	dependencies := []cdxDependency{
		{Ref: dataRef, DependsOn: []string{signalsRef}},
		{Ref: signalsRef, DependsOn: signalsDeps},
		{Ref: bomDumpsRef, DependsOn: []string{}},
		{Ref: bomPageviewsRef, DependsOn: []string{}},
	}

	// Item signals built by releases before the osmviews_score column
	// have no OSMViews in their provenance record.
	if ov := prov.OSMViews; ov != nil {
		hashes := []cdxHash{{Alg: "SHA-256", Content: ov.SHA256}}
		if ov.SHA512 != "" {
			hashes = append(hashes, cdxHash{Alg: "SHA-512", Content: ov.SHA512})
		}
		components = append(components, cdxComponent{
			Type:        "data",
			BOMRef:      bomOSMViewsRef,
			Supplier:    bomSupplier(),
			Name:        "osmviews",
			Version:     ov.Version,
			Description: "OSMViews: how often each place on Earth is viewed on OpenStreetMap-based maps (Cloud-Optimized GeoTIFF). Source of the osmviews_score column.",
			PURL:        ov.PURL,
			Licenses:    []cdxLicenseChoice{{License: cdxLicense{ID: "CC0-1.0"}}},
			Hashes:      hashes,
			ExternalReferences: []cdxExternalRef{
				{Type: "distribution", URL: ov.URL},
				{Type: "website", URL: bomOSMViewsURL},
				{Type: "bom", URL: ov.BOMURL, Hashes: []cdxHash{{Alg: "SHA-256", Content: ov.BOMSHA256}}},
			},
		})
		inputs = append(inputs, cdxWorkflowIO{Resource: &cdxResourceRef{Ref: bomOSMViewsRef}})
		dependencies[1].DependsOn = append(signalsDeps, bomOSMViewsRef)
		dependencies = append(dependencies, cdxDependency{Ref: bomOSMViewsRef, DependsOn: []string{}})
	}

	workflow := cdxWorkflow{
		BOMRef: "qrank-workflow-" + ymd,
		UID:    "qrank-build-" + ymd,
		Name:   "QRank build",
		Description: fmt.Sprintf("Ranks Wikidata items by %d weeks of Wikimedia pageviews "+
			"(%s..%s). Intermediate files are reused from earlier runs, "+
			"so more than one builder version can be listed.",
			prov.Pageviews.Weeks, prov.Pageviews.FirstDay, prov.Pageviews.LastDay),
		ResourceReferences: toolRefs,
		TaskTypes:          []string{"build"},
		Inputs:             inputs,
		Outputs: []cdxWorkflowIO{
			{Type: "artifact", Resource: &cdxResourceRef{Ref: signalsRef}},
			{Type: "artifact", Resource: &cdxResourceRef{Ref: dataRef}},
		},
	}

	return &cdxBOM{
		Schema:       bomSchema,
		BOMFormat:    "CycloneDX",
		SpecVersion:  bomSpecVersion,
		SerialNumber: "urn:uuid:" + uuid.NewSHA1(bomNamespace, []byte(in.SHA256)).String(),
		Version:      1,
		Metadata: cdxMetadata{
			Timestamp:  in.Date.UTC().Format(time.RFC3339),
			Lifecycles: []cdxLifecycle{{Phase: "post-build"}},
			Supplier:   bomSupplier(),
			Tools:      cdxTools{Components: tools},
			Component:  data,
		},
		Components:   components,
		Dependencies: dependencies,
		Formulation: []cdxFormulation{{
			BOMRef:    "qrank-build-" + ymd,
			Workflows: []cdxWorkflow{workflow},
		}},
	}
}

// Minimal CycloneDX 1.7 JSON model, covering only the fields the builder
// emits. Field order is the JSON output order; keep it stable.

type cdxBOM struct {
	Schema       string           `json:"$schema"`
	BOMFormat    string           `json:"bomFormat"`
	SpecVersion  string           `json:"specVersion"`
	SerialNumber string           `json:"serialNumber"`
	Version      int              `json:"version"`
	Metadata     cdxMetadata      `json:"metadata"`
	Components   []cdxComponent   `json:"components"`
	Dependencies []cdxDependency  `json:"dependencies"`
	Formulation  []cdxFormulation `json:"formulation,omitempty"`
}

type cdxMetadata struct {
	Timestamp  string         `json:"timestamp"`
	Lifecycles []cdxLifecycle `json:"lifecycles"`
	Supplier   *cdxOrgEntity  `json:"supplier,omitempty"`
	Tools      cdxTools       `json:"tools"`
	Component  cdxComponent   `json:"component"`
}

type cdxLifecycle struct {
	Phase string `json:"phase"`
}

type cdxOrgEntity struct {
	Name string   `json:"name"`
	URL  []string `json:"url,omitempty"`
}

type cdxTools struct {
	Components []cdxComponent `json:"components"`
}

type cdxComponent struct {
	Type               string             `json:"type"`
	BOMRef             string             `json:"bom-ref,omitempty"`
	Supplier           *cdxOrgEntity      `json:"supplier,omitempty"`
	Name               string             `json:"name"`
	Group              string             `json:"group,omitempty"`
	Version            string             `json:"version,omitempty"`
	Description        string             `json:"description,omitempty"`
	Publisher          string             `json:"publisher,omitempty"`
	PURL               string             `json:"purl,omitempty"`
	Licenses           []cdxLicenseChoice `json:"licenses,omitempty"`
	Hashes             []cdxHash          `json:"hashes,omitempty"`
	ExternalReferences []cdxExternalRef   `json:"externalReferences,omitempty"`
	Data               []cdxComponentData `json:"data,omitempty"`
	Properties         []cdxProperty      `json:"properties,omitempty"`
}

type cdxLicenseChoice struct {
	License cdxLicense `json:"license"`
}

type cdxLicense struct {
	ID string `json:"id,omitempty"`
}

type cdxHash struct {
	Alg     string `json:"alg"`
	Content string `json:"content"`
}

type cdxExternalRef struct {
	Type   string    `json:"type"`
	URL    string    `json:"url"`
	Hashes []cdxHash `json:"hashes,omitempty"`
}

type cdxComponentData struct {
	BOMRef         string `json:"bom-ref,omitempty"`
	Type           string `json:"type"`
	Name           string `json:"name,omitempty"`
	Classification string `json:"classification,omitempty"`
}

type cdxProperty struct {
	Name  string `json:"name"`
	Value string `json:"value"`
}

type cdxDependency struct {
	Ref       string   `json:"ref"`
	DependsOn []string `json:"dependsOn"`
}

type cdxFormulation struct {
	BOMRef    string        `json:"bom-ref,omitempty"`
	Workflows []cdxWorkflow `json:"workflows,omitempty"`
}

type cdxWorkflow struct {
	BOMRef             string           `json:"bom-ref"`
	UID                string           `json:"uid"`
	Name               string           `json:"name,omitempty"`
	Description        string           `json:"description,omitempty"`
	ResourceReferences []cdxResourceRef `json:"resourceReferences,omitempty"`
	TaskTypes          []string         `json:"taskTypes"`
	Inputs             []cdxWorkflowIO  `json:"inputs,omitempty"`
	Outputs            []cdxWorkflowIO  `json:"outputs,omitempty"`
}

type cdxResourceRef struct {
	Ref string `json:"ref,omitempty"`
}

// cdxWorkflowIO models both a CycloneDX inputType and outputType; Type is set
// only for outputs (e.g. "artifact").
type cdxWorkflowIO struct {
	Type     string          `json:"type,omitempty"`
	Resource *cdxResourceRef `json:"resource,omitempty"`
}
